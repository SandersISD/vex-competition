// MotionLib: pure-pursuit follower for a tank drive (VEX V5, bare metal).
// Legacy follow() keeps last-moving-point stopping. Optional followSegment()
// supports endpoint-bounded forward/reverse travel and returns an exit status.
//
// Typing path points: x/y in INCHES, speed in motor % (0-100).
// The robot chases a point `lookahead` inches ahead along the path; the
// left/right wheel split comes from the arc through that point.
//
// Telemetry prints to the brain you pass in — every robot's own object.
#pragma once

#include "vex.h"
#include "MotionLib/Odom.hpp"
#include <math.h>
#include <cmath>

// One point of a generated path: field x/y (inches) + cruise speed (motor %).
// Generated by path2h.py from path.jerryio.com (LemLib Tarball v0.5).
//
// GLOBAL ON PURPOSE: generated path headers declare
//   static const PathPoint path[] = {...};
// unqualified and must keep compiling unchanged.
struct PathPoint {
  double x;     // inches
  double y;     // inches
  double speed; // motor % (0-100)
};

// One drawn waypoint (end-point) of a generated path: where the robot
// should BE at the ends of meaningful segments - the hook for endpoint
// robot controls (intake / gate / shoot on arrival).
//   x, y       inches, same field frame as PathPoint
//   heading    facing degrees drawn in jerryio (same compass frame);
//              -1 = the drawing never set one (jerryio then means its
//              default 0 - VERIFY the drawing before treating it as real)
//   pts_index  index into the companion PathPoint[] sample array (pass to
//              followSegment() on an endpoint-bounded slice to target it);
//              -1 = no matching sample row
//
// GLOBAL ON PURPOSE: generated path headers declare
//   static const PathEndpoint path_endpoints[] = {...};
// unqualified and must keep compiling unchanged.
struct PathEndpoint {
  double x;       // inches
  double y;       // inches
  double heading; // degrees (drawn); -1 = not drawn
  int pts_index;  // row in the companion PathPoint[]; -1 = none
};

namespace motion {

enum class PathDirection { Forward, Reverse, Auto };
enum class FollowResult { Reached, Timeout, Invalid, MissedEndpoint };


class Pursuit {
public:
  // odom: the library odometry you also drive the primitives with.
  // ui:   your brain -- telemetry ("cur/dEnd" etc) prints there.
  Pursuit(Odom& odom, vex::motor_group& left, vex::motor_group& right,
          vex::brain& ui, double track_width_in, double lookahead_in = 10.0)
      : track_width(track_width_in), lookahead(lookahead_in),
        _odom(&odom), _left(&left), _right(&right), _ui(&ui) {}

  double track_width; // inches between left/right wheel contact points
  double lookahead;    // inches; bigger = smoother, smaller = tighter
                       // 10.0 is a STARTER VALUE - tune on your robot

  // 0.1.1 speed shaping. The follower used to command cruise % as an instant
  // step (path start, corner entries) and arrived at the last moving point
  // under power. Two knobs shape the command instead (both tune-me defaults):
  double max_accel = 150.0;    // pct per second accel slew limit on the
                               // speed command (decel is NOT limited, so the
                               // end taper engages immediately)
  double end_decel_zone = 8.0; // inches before the last moving point where
                               // cruise % tapers down (0 disables)
  double end_min_speed = 6.0;  // taper floor in pct - keeps the final crawl
                               // moving so the run still converges

  // Blocking: drives the path, ends within ~2" of the last moving point
  // (or timeout). Trailing zero-speed points (decel tail / stray exports)
  // are never chased.
  // last_pt (optional): index into pts[] to finish at once reached - pass a
  // drawn waypoint's pts_index from the generated path header to follow only
  // part of the path, take an action, then follow the rest. -1 (default)
  // follows the whole path as usual.
  // stall_timeout_ms: stop after this long without path progress; 0 disables.
  // The existing total timeout still applies independently.
  void follow(const PathPoint* pts, int len, double speed_scale = 1.0,
              int last_pt = -1, int stall_timeout_ms = 0) {
    if (len < 2) return;
    run(pts, len, speed_scale, last_pt, false, false, stall_timeout_ms);
  }

  // pts is ONE segment only, ending at a drawn endpoint. Auto chooses once
  // from current heading vs departure tangent; ambiguous sideways starts fail.
  FollowResult followSegment(const PathPoint* pts, int len, double speed_scale,
                             PathDirection direction = PathDirection::Auto) {
    if (!pts || len < 2 || !std::isfinite(speed_scale) ||
        speed_scale <= 0.0 || speed_scale > 1.0 ||
        !std::isfinite(track_width) || track_width <= 0.0 ||
        !std::isfinite(lookahead) || lookahead <= 0.0 ||
        !std::isfinite(max_accel) || max_accel <= 0.0 ||
        !std::isfinite(end_min_speed) || end_min_speed <= 0.0 ||
        !std::isfinite(end_decel_zone) || end_decel_zone <= 0.0)
      return invalid();
    bool moving = false;
    for (int i = 0; i < len; ++i) {
      if (!std::isfinite(pts[i].x) || !std::isfinite(pts[i].y) ||
          !std::isfinite(pts[i].speed) || pts[i].speed < 0.0 || pts[i].speed > 100.0)
        return invalid();
      moving = moving || pts[i].speed > 0.0;
    }
    if (!moving) return invalid();
    _odom->update();
    if (_dist(_odom->get_x(), _odom->get_y(), pts[0]) > 3.0)
      return invalid(); // do not chase a disconnected start
    bool reverse = direction == PathDirection::Reverse;
    if (direction == PathDirection::Auto) {
      int next = 1;
      while (next < len && _dist(pts[0], pts[next]) < 0.05) ++next;
      if (next == len) return invalid();
      const double dx = pts[next].x - pts[0].x;
      const double dy = pts[next].y - pts[0].y;
      const double h = _odom->get_theta() * M_PI / 180.0;
      const double alignment = (dx * sin(h) + dy * cos(h)) / hypot(dx, dy);
      if (!std::isfinite(alignment) || fabs(alignment) < 0.5)
        return invalid(); // within 30 degrees of sideways: require explicit direction
      reverse = alignment < 0.0;
    } else if (direction != PathDirection::Forward && direction != PathDirection::Reverse) {
      return invalid();
    }
    _ui->Screen.printAt(10, 170, reverse ? "segment: REVERSE" : "segment: FORWARD");
    return run(pts, len, speed_scale, len - 1, true, reverse);
  }

private:
  FollowResult invalid() {
    _left->stop(vex::brake);
    _right->stop(vex::brake);
    _ui->Screen.printAt(10, 80, "EXIT: INVALID segment");
    return FollowResult::Invalid;
  }

  FollowResult run(const PathPoint* pts, int len, double speed_scale,
                   int last_pt, bool segment, bool reverse, int stall_timeout_ms = 0) {

    // Last point that actually moves; the robot finishes within 2" of it.
    int end_index = len - 1;
    if (last_pt >= 0 && last_pt < len) end_index = last_pt;
    if (!segment)
      while (end_index > 0 && pts[end_index].speed <= 0.0) end_index--;

    double length = 0.0; // path length, for the timeout estimate
    for (int i = 1; i < len; i++)
      length += _dist(pts[i - 1], pts[i]);

    int cursor = 0;
    vex::timer t;
    t.reset();
    const int timeout = 3000 + (int)(length * 60.0 / fmax(speed_scale, 0.1)); // ms

    bool reached = false;
    bool missed = false;
    bool stalled = false;
    double furthest_progress = -HUGE_VAL;
    double progress_ms = 0.0;
    int iter = 0;
    double v_out = 0.0; // slewed speed command (pct)

    while (t.time(vex::msec) < timeout) {
      _odom->update();
      double rx = _odom->get_x();
      double ry = _odom->get_y();
      double th = (_odom->get_theta() + (reverse ? 180.0 : 0.0)) * M_PI / 180.0;
      if (segment && (!std::isfinite(rx) || !std::isfinite(ry) || !std::isfinite(th)))
        return invalid();

      // 1) Advance cursor to the nearest of the next few points (forward only)
      int last = cursor + 6;
      if (last > end_index) last = end_index;
      double best = _dist(rx, ry, pts[cursor]);
      for (int j = cursor + 1; j <= last; j++) {
        double d = _dist(rx, ry, pts[j]);
        if (d < best) { best = d; cursor = j; }
      }

      // 2) Done once the last moving point is reached
      const double d_end = _dist(rx, ry, pts[end_index]);
      if ((segment && d_end < 2.0) ||
          (!segment && cursor >= end_index && best < 2.0)) {
        reached = true; break;
      }

      // Project onto the segments adjacent to the cursor. Require a new
      // forward high-water mark of 0.25 inch; jitter must not reset the timer.
      if (stall_timeout_ms > 0) {
        const double progress = _pathProgress(rx, ry, pts, cursor, end_index);
        if (progress > furthest_progress + 0.25) {
          furthest_progress = progress;
          progress_ms = t.time(vex::msec);
        }
        if (t.time(vex::msec) - progress_ms >= stall_timeout_ms) {
          stalled = true;
          break;
        }
      }

      // 3) Lookahead point: first point at least `lookahead` away,
      //    never beyond the last moving point
      int li = cursor;
      while (li < end_index && _dist(rx, ry, pts[li]) < lookahead) li++;

      // 4) Curvature of the arc through the lookahead point (robot frame)
      double dx = pts[li].x - rx;
      double dy = pts[li].y - ry;
      double L = sqrt(dx * dx + dy * dy);
      if (L < 0.001) { vex::wait(10, vex::msec); continue; }

      double fwd   = dx * sin(th) + dy * cos(th); // component along robot forward
      double right = dx * cos(th) - dy * sin(th); // component to robot's right
      double alpha = atan2(right, fwd);           // + = target is to the right
      double k = (2.0 * sin(alpha)) / L;          // arc curvature, 1/inch

      // If a terminal target has been passed, fail rather than orbit it.
      if (segment && d_end < 4.0 &&
          (pts[end_index].x - rx) * sin(th) +
          (pts[end_index].y - ry) * cos(th) < 0.0) {
        missed = true; break;
      }

      double base = pts[li].speed * speed_scale;
      if (segment && pts[li].speed == 0.0) {
        int moving = li;
        while (moving > 0 && pts[moving].speed == 0.0) --moving;
        base = fmax(pts[moving].speed, end_min_speed) * speed_scale;
      }

      // End taper: inside end_decel_zone of the final moving point, ramp the
      // command down toward end_min_speed so the robot ARRIVES slow instead
      // of braking from cruise (the classic overshoot).
      if (end_decel_zone > 0.0 && end_index > 0) {
        double d_end = _dist(rx, ry, pts[end_index]);
        if (d_end < end_decel_zone) {
          double taper = d_end / end_decel_zone; // 1 at zone edge -> 0 at end
          double floor_v = fmin(base, end_min_speed * speed_scale);
          base = floor_v + (base - floor_v) * taper;
        }
      }

      // Accel slew: ramp the commanded speed up at max_accel pct/s. Only
      // limits acceleration - drops toward a slower target are instant, so
      // corner entries and the end taper engage immediately.
      double dv = base - v_out;
      double step = max_accel * 0.01; // loop ticks every 10 ms
      if (dv > step) dv = step;
      v_out += dv;
      base = v_out;

      double left_out  = base * (1.0 + k * track_width / 2.0);
      double right_out = base * (1.0 - k * track_width / 2.0);
      double m = fmax(fabs(left_out), fabs(right_out));
      if (m > 100.0) { left_out *= 100.0 / m; right_out *= 100.0 / m; }

      if (reverse) {
        // Virtual backward-facing robot: swap and negate its wheel commands.
        const double virtual_left = left_out;
        left_out = -right_out;
        right_out = -virtual_left;
      }
      _left->spin(vex::forward, left_out, vex::pct);
      _right->spin(vex::forward, right_out, vex::pct);

      // Live telemetry every ~100ms: shows WHY the run behaves as it does.
      //   cur stalls / dEnd barely shrinks -> pods not reading (direction/port)
      //   H drifts vs physical        -> start heading mismatch
      //   X,Y diverge from physical   -> pod scale or swapped pods
      if (iter++ % 10 == 0) {
        _ui->Screen.printAt(10, 20, "t:%5.1f X:%6.1f Y:%6.1f H:%6.1f",
                            t.time(vex::sec), rx, ry, _odom->get_theta());
        _ui->Screen.printAt(10, 50, "cur:%2d/%2d dEnd:%5.1f li:%2d v:%4.1f",
                            cursor, end_index,
                            _dist(rx, ry, pts[end_index]), li, base);
      }
      vex::wait(10, vex::msec);
    }

    // Exit report: reached the end, or gave up (timeout = never converged)
    _odom->update();
    _ui->Screen.printAt(10, 80, reached ? "EXIT: reached end" :
                         (missed ? "EXIT: MISSED endpoint" :
                          (stalled ? "EXIT: STALLED" : "EXIT: TIMEOUT")));
    _ui->Screen.printAt(10, 110, "final X:%6.1f Y:%6.1f H:%6.1f",
                         _odom->get_x(), _odom->get_y(), _odom->get_theta());
    _ui->Screen.printAt(10, 140, "dEnd:%5.1f t:%5.1fs",
                         _dist(_odom->get_x(), _odom->get_y(), pts[end_index]),
                         t.time(vex::sec));

    _left->stop(vex::brake);
    _right->stop(vex::brake);
    return reached ? FollowResult::Reached :
           (missed ? FollowResult::MissedEndpoint : FollowResult::Timeout);
  }

private:
  Odom* _odom;
  vex::motor_group* _left;
  vex::motor_group* _right;
  vex::brain* _ui;

  static double _pathProgress(double x, double y, const PathPoint* pts,
                              int cursor, int end_index) {
    if (end_index == 0) return 0.0;
    const int first = cursor > 0 ? cursor - 1 : 0;
    const int last = cursor < end_index ? cursor : end_index - 1;
    double prefix = 0.0;
    for (int i = 1; i <= first; ++i) prefix += _dist(pts[i - 1], pts[i]);
    double nearest = HUGE_VAL, progress = prefix;
    for (int i = first; i <= last; ++i) {
      const double dx = pts[i + 1].x - pts[i].x;
      const double dy = pts[i + 1].y - pts[i].y;
      const double length = hypot(dx, dy);
      const double fraction = length > 0.001 ?
          fmax(0.0, fmin(1.0, ((x - pts[i].x) * dx +
                              (y - pts[i].y) * dy) / (length * length))) : 0.0;
      const double distance = hypot(x - pts[i].x - fraction * dx,
                                    y - pts[i].y - fraction * dy);
      if (distance < nearest) {
        nearest = distance;
        progress = prefix + fraction * length;
      }
      prefix += length;
    }
    return progress;
  }

  static double _dist(double x1, double y1, const PathPoint& p) {
    double dx = p.x - x1, dy = p.y - y1;
    return sqrt(dx * dx + dy * dy);
  }
  static double _dist(const PathPoint& a, const PathPoint& b) {
    double dx = b.x - a.x, dy = b.y - a.y;
    return sqrt(dx * dx + dy * dy);
  }
};

} // namespace motion
